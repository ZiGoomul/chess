export function findCourse(id) {
    return openingCourses.find(course => course.id === id) || null;
}

export function findLine(id) {
    for (const course of openingCourses) {
        const line = course.lines.find(item => item.id === id);
        if (line) return { course, line };
    }
    return null;
}
